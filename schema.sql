-- PRISM PostgreSQL schema.
--
-- Idempotent: every statement is CREATE ... IF NOT EXISTS, so it is safe to
-- run repeatedly. The app applies this file itself on startup (database.py,
-- init_schema) unless DB_AUTO_SCHEMA=0; a DBA who would rather own the DDL can
-- apply it by hand instead:
--
--     psql "$DATABASE_URL" -f schema.sql
--
-- Conventions
--   * Timestamps are Unix epoch seconds stored as DOUBLE PRECISION (the same
--     float the app has always written with time.time()). Do NOT use REAL:
--     PostgreSQL's REAL is 4 bytes and cannot hold an epoch to the second.
--   * Flag columns (is_active, done, ...) stay 0/1 INTEGERs, as before.
--   * Surrogate keys are identity columns that accept explicit values
--     (GENERATED BY DEFAULT), which is what lets migrate_sqlite_to_postgres.py
--     keep the original ids.
--   * No FOREIGN KEYs, matching the old SQLite schema (which never enforced
--     them). Group deletion and trailer ownership are handled in the app.
--   * New columns added after this file ships go in as
--     ALTER TABLE ... ADD COLUMN IF NOT EXISTS, below the CREATE they extend.

-- ---- Accounts ----
CREATE TABLE IF NOT EXISTS users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username          TEXT NOT NULL UNIQUE,
    password_hash     TEXT NOT NULL,
    role              TEXT NOT NULL DEFAULT 'user',
    is_active         INTEGER NOT NULL DEFAULT 1,
    created_at        DOUBLE PRECISION NOT NULL,
    last_login        DOUBLE PRECISION,
    -- Legacy single group, from before an account could be in several. Moved
    -- into user_groups below and cleared; nothing reads it any more.
    group_id          BIGINT,
    -- TOTP two-factor. totp_enabled only flips to 1 after a code is verified;
    -- totp_backup_codes holds newline-separated hashes of one-time codes.
    totp_secret       TEXT,
    totp_enabled      INTEGER NOT NULL DEFAULT 0,
    totp_backup_codes TEXT,
    -- Per-account lockout, alongside the per-IP rate limit.
    failed_logins     INTEGER NOT NULL DEFAULT 0,
    locked_until      DOUBLE PRECISION
);

-- Bumped whenever an account's sign-ins must end (password set or reset,
-- disabled, two-factor reset): a session remembers the value it started with,
-- and stops working once they differ (see _revalidate_session in auth.py).
ALTER TABLE users ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL DEFAULT 0;
-- The 30-second step of the last two-factor code accepted, so the same code
-- cannot be used twice while it is still valid.
ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_last_step BIGINT;

CREATE TABLE IF NOT EXISTS groups (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL UNIQUE,
    created_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS group_permissions (
    group_id   BIGINT NOT NULL,
    permission TEXT NOT NULL,
    PRIMARY KEY (group_id, permission)
);

-- Which groups each account is in (any number). An account's tabs are every
-- tab any of its groups grants; with no group it gets only the ungated ones
-- (see user_can in auth.py). Admins are not limited by groups.
CREATE TABLE IF NOT EXISTS user_groups (
    user_id  BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, group_id)
);
CREATE INDEX IF NOT EXISTS idx_user_groups_group ON user_groups (group_id);

-- One-time move of the old single users.group_id into user_groups. Clearing
-- the old column afterwards is what makes this safe to run on every start:
-- a membership an admin later removes is not brought back.
INSERT INTO user_groups (user_id, group_id)
    SELECT u.id, u.group_id FROM users u JOIN groups g ON g.id = u.group_id
    ON CONFLICT DO NOTHING;
UPDATE users SET group_id = NULL WHERE group_id IS NOT NULL;

-- ---- Trailer library, audit trail, network browser ----
CREATE TABLE IF NOT EXISTS audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at DOUBLE PRECISION NOT NULL,
    user_id    BIGINT,
    username   TEXT,
    action     TEXT NOT NULL,
    target     TEXT,
    detail     TEXT,
    ip         TEXT
);

CREATE TABLE IF NOT EXISTS network_favorites (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    category   TEXT NOT NULL,
    path       TEXT NOT NULL,
    label      TEXT,
    created_at DOUBLE PRECISION NOT NULL,
    UNIQUE (user_id, category, path)
);

-- Named, admin-managed "Send to <name>" delivery targets (e.g. a Vantage watch
-- folder or a MAM ingest). Global, like the other network categories, not
-- per-user like favorites: a facility's delivery targets are shared
-- infrastructure. delivery_kind (video | csv | csv_video | fcpxml, validated in
-- library_db.py) controls what "Send to" writes there.
--   include_fcpxml      legacy opt-in that was removed from the UI; kept so a
--                       value already stored on a destination still loads.
--   fcpxml_audio_tracks whether the FCP XML embeds audio clipitems for the
--                       surviving music/VO/card materials or stays video-only.
CREATE TABLE IF NOT EXISTS network_destinations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL,
    path                TEXT NOT NULL,
    username            TEXT,
    password            TEXT,
    delivery_kind       TEXT NOT NULL DEFAULT 'video',
    include_fcpxml      INTEGER NOT NULL DEFAULT 0,
    fcpxml_audio_tracks INTEGER NOT NULL DEFAULT 0,
    created_at          DOUBLE PRECISION NOT NULL,
    updated_at          DOUBLE PRECISION NOT NULL
);

-- user_id/username NULL = saved before accounts existed = admin-only.
CREATE TABLE IF NOT EXISTS trailers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orig_name        TEXT,
    filename         TEXT NOT NULL,
    created_at       DOUBLE PRECISION NOT NULL,
    trailer_duration DOUBLE PRECISION,
    video_duration   DOUBLE PRECISION,
    trailer_length   TEXT,
    bgm_source       TEXT,
    sfx_source       TEXT,
    vo_source        TEXT,
    result_json      TEXT,
    user_id          BIGINT,
    username         TEXT
);

-- A saved Episodic Plug belongs to a project (project_routes.py), the way a
-- batch of Vertical Shorts does. NULL for a plug made before projects, or
-- whose project has since been deleted: such a plug is shown as not filed.
ALTER TABLE trailers ADD COLUMN IF NOT EXISTS project_id TEXT;
CREATE INDEX IF NOT EXISTS idx_trailers_project ON trailers (project_id);

-- ---- Background jobs (promo / shorts / schedule share one table and queue) ----
CREATE TABLE IF NOT EXISTS jobs (
    id               TEXT PRIMARY KEY,
    percent          INTEGER NOT NULL DEFAULT 0,
    step             TEXT,
    done             INTEGER NOT NULL DEFAULT 0,
    error            TEXT,
    status           TEXT,
    result_json      TEXT,
    cancel_requested INTEGER NOT NULL DEFAULT 0,
    created          DOUBLE PRECISION NOT NULL,
    user_id          BIGINT,
    username         TEXT,
    orig_name        TEXT,
    kind             TEXT
);

-- ---- AI chat memory (strictly per user) ----
CREATE TABLE IF NOT EXISTS chat_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    role       TEXT NOT NULL,
    content    TEXT NOT NULL,
    images     TEXT,
    created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_chat_messages_user ON chat_messages (user_id, id);

-- ---- Per-show templates ----
-- One <slot>_file / <slot>_name pair per asset slot (pipeline.TEMPLATE_SLOTS);
-- tests/test_database_schema.py fails if a slot is added in code but not here.
-- _file is the stored filename inside TEMPLATES_DIR, _name the original name.
CREATE TABLE IF NOT EXISTS show_templates (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL UNIQUE,
    notes               TEXT,
    created_at          DOUBLE PRECISION NOT NULL,
    updated_at          DOUBLE PRECISION NOT NULL,
    genre               TEXT,
    transition          TEXT,
    xfade_dur           DOUBLE PRECISION,
    settings_json       TEXT,
    vo_start            DOUBLE PRECISION,
    vo_volume           DOUBLE PRECISION,
    vo_trim_start       DOUBLE PRECISION,
    vo_trim_end         DOUBLE PRECISION,
    title_card_vo_start DOUBLE PRECISION,
    title_card_vo_end   DOUBLE PRECISION,
    end_card_vo_start   DOUBLE PRECISION,
    end_card_vo_end     DOUBLE PRECISION,
    bgm_file            TEXT,
    bgm_name            TEXT,
    sfx_file            TEXT,
    sfx_name            TEXT,
    vo_file             TEXT,
    vo_name             TEXT,
    title_card_file     TEXT,
    title_card_name     TEXT,
    title_card_vo_file  TEXT,
    title_card_vo_name  TEXT,
    end_card_file       TEXT,
    end_card_name       TEXT,
    end_card_vo_file    TEXT,
    end_card_vo_name    TEXT
);
